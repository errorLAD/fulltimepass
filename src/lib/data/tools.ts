/**
 * Returns localized tools based on language.
 */
export function getLocalizedTools(language: Language): ToolDefinition[] {
  if (language === "hi") {
    return TOOLS;
  }
  return TOOLS.map((t) => ({
    ...t,
    title: t.titleEn || t.title,
    tagline: t.taglineEn || t.tagline,
    description: t.descriptionEn || t.description,
    badge: t.badgeEn || t.badge,
  }));
}

/**
 * Returns localized tool by slug.
 */
export function getLocalizedTool(slug: string, language: Language): ToolDefinition | undefined {
  const tool = TOOLS.find((t) => t.slug === slug);
  if (!tool) return undefined;
  if (language === "hi") return tool;
  return {
    ...tool,
    title: tool.titleEn || tool.title,
    tagline: tool.taglineEn || tool.tagline,
    description: tool.descriptionEn || tool.description,
    badge: tool.badgeEn || tool.badge,
  };
}

/**
 * Returns localized categories based on language.
 */
export function getLocalizedCategories(language: Language) {
  return CATEGORIES.map((c) => ({
    ...c,
    desc: language === "en" ? c.descEn : c.desc,
  }));
}
